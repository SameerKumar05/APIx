class TestMasterDataAlignment:
    """Validates that routes and airlines match across Ingestion config and Database seeds."""

    def test_route_definitions_match_between_ingestion_and_db_seed(self) -> None:
        """The 14 standard DGCA domestic corridors must exist in both Ingestion and Database seeds."""
        ingestion_route_codes = {r.pair_key for r in DEFAULT_ROUTES}
        db_route_codes = {f"{r['origin']}-{r['destination']}" for r in INITIAL_ROUTES}

        assert len(ingestion_route_codes) == 14
        assert len(db_route_codes) == 14
        assert ingestion_route_codes == db_route_codes

        expected_pairs = {
            "DEL-BOM",
            "BOM-DEL",
            "BLR-DEL",
            "DEL-BLR",
            "BOM-BLR",
            "BLR-BOM",
            "DEL-CCU",
            "CCU-DEL",
            "DEL-HYD",
            "HYD-DEL",
            "DEL-MAA",
            "MAA-DEL",
            "BLR-HYD",
            "HYD-BLR",
        }
        assert ingestion_route_codes == expected_pairs

    def test_dgca_route_weights_sum_to_one(self) -> None:
        """Route traffic weights must sum to 1.000 (100% of monitored basket) in all layers."""
        # 1. Ingestion config route weights
        ingestion_weights_sum = sum(r.dgca_weight for r in DEFAULT_ROUTES)
        assert pytest.approx(ingestion_weights_sum, abs=1e-5) == 1.0

        # 2. Database seed route weights
        db_weights_sum = sum(r["weight"] for r in INITIAL_ROUTES)
        assert pytest.approx(db_weights_sum, abs=1e-5) == 1.0

        # 3. Quant engine default route traffic shares
        quant_weights_sum = sum(DEFAULT_DGCA_ROUTE_TRAFFIC_SHARES.values())
        assert pytest.approx(quant_weights_sum, abs=1e-5) == 1.0

    def test_airline_definitions_match_between_ingestion_and_db_seed(self) -> None:
        """All 5 major domestic carriers match in codes and market share weights."""
        ingestion_airline_codes = {a.code for a in AIRLINES}
        db_airline_codes = {a["code"] for a in INITIAL_AIRLINES}
        quant_airline_codes = set(DEFAULT_AIRLINE_MARKET_SHARES.keys())

        expected_carriers = {"6E", "AI", "IX", "QP", "SG"}
        assert ingestion_airline_codes == expected_carriers
        assert db_airline_codes == expected_carriers
        assert quant_airline_codes == expected_carriers

        # Modelled shares mirroring ingestion.config.AIRLINES, not DGCA figures.
        assert DEFAULT_AIRLINE_MARKET_SHARES["6E"] == 0.60
        assert DEFAULT_AIRLINE_MARKET_SHARES["AI"] == 0.15
        assert DEFAULT_AIRLINE_MARKET_SHARES["IX"] == 0.10
        assert DEFAULT_AIRLINE_MARKET_SHARES["QP"] == 0.10
        assert DEFAULT_AIRLINE_MARKET_SHARES["SG"] == 0.05

        # Database seed INITIAL_AIRLINES must mirror this at 100.0% sum
        db_airline_shares = {a["code"]: a["market_share_pct"] for a in INITIAL_AIRLINES}
        assert db_airline_shares["6E"] == 60.0
        assert db_airline_shares["AI"] == 15.0
        assert db_airline_shares["IX"] == 10.0
        assert db_airline_shares["QP"] == 10.0
        assert db_airline_shares["SG"] == 5.0
        assert pytest.approx(sum(db_airline_shares.values()), abs=1e-9) == 100.0

        # These previously summed to 0.99, which under-weighted every carrier.
        total_market_share = sum(DEFAULT_AIRLINE_MARKET_SHARES.values())
        assert pytest.approx(total_market_share, abs=1e-9) == 1.0

        # Seed market shares must sum to 100% and match
        db_seed_sum = sum(a["market_share_pct"] for a in INITIAL_AIRLINES)
        assert pytest.approx(db_seed_sum, abs=1e-9) == 100.0
        for a in INITIAL_AIRLINES:
            assert a["market_share_pct"] == pytest.approx(
                DEFAULT_AIRLINE_MARKET_SHARES[a["code"]] * 100.0
            )

    def test_booking_windows_standardization(self) -> None:
        """The 5 standard booking windows (T+1, T+7, T+15, T+30, T+45) match across subsystems."""
        codes = [w.code for w in BOOKING_WINDOWS]
        assert codes == ["T+1", "T+7", "T+15", "T+30", "T+45"]

        days = [w.days_advance for w in BOOKING_WINDOWS]
        assert days == [1, 7, 15, 30, 45]

        # Quant engine weights sum to 1.0
        window_weights_sum = sum(DEFAULT_BOOKING_WINDOW_WEIGHTS.values())
        assert pytest.approx(window_weights_sum, abs=1e-5) == 1.0

        # Index pipeline weights match and contain all 5 windows
        from backend.app.services.index_pipeline import (
            CANONICAL_WINDOWS,
            DEFAULT_WINDOW_WEIGHTS,
        )

        assert set(CANONICAL_WINDOWS) == {"T+1", "T+7", "T+15", "T+30", "T+45"}
        for w in codes:
            assert w in DEFAULT_WINDOW_WEIGHTS
            raw_w = w.replace("+", "")
            assert DEFAULT_WINDOW_WEIGHTS[w] == pytest.approx(
                DEFAULT_BOOKING_WINDOW_WEIGHTS[raw_w]
            )


