class TestIngestionToDatabaseContract:
    """Validates data flow and type compatibility between Ingestion/API and SQLAlchemy models."""

    def test_raw_fare_orm_creation_and_persistence(
        self,
        db_session: Session,
        sample_ingestion_record: IngestionRawFareRecord,
    ) -> None:
        """RawFare ORM model can be constructed from ingestion record and persisted."""
        flight_date_obj = date.fromisoformat(
            sample_ingestion_record.flight_date
            or sample_ingestion_record.departure_datetime[:10]
        )
        dep_time = datetime.fromisoformat(
            sample_ingestion_record.departure_datetime
        ).replace(tzinfo=UTC)
        arr_time = (
            datetime.fromisoformat(sample_ingestion_record.arrival_datetime).replace(
                tzinfo=UTC
            )
            if sample_ingestion_record.arrival_datetime
            else None
        )
        booking_time = datetime.fromisoformat(
            sample_ingestion_record.booking_datetime
        ).replace(tzinfo=UTC)

        db_fare = DbRawFare(
            batch_id="batch-test-contract-01",
            origin=sample_ingestion_record.origin,
            destination=sample_ingestion_record.destination,
            flight_date=flight_date_obj,
            booking_window=sample_ingestion_record.booking_window or "T+7",
            airline_code=sample_ingestion_record.airline_code,
            flight_number=sample_ingestion_record.flight_number,
            departure_time=dep_time,
            arrival_time=arr_time,
            duration_minutes=135,
            stops=sample_ingestion_record.stops,
            fare_class="Economy",
            base_fare=sample_ingestion_record.base_fare or 4200.0,
            taxes_and_fees=sample_ingestion_record.taxes_and_fees or 1220.0,
            total_fare=sample_ingestion_record.fare_inr,
            source_platform=sample_ingestion_record.source,
            scraped_at=booking_time,
            hash_id=sample_ingestion_record.generate_dedup_hash(),
            is_synthetic=False,
        )

        db_session.add(db_fare)
        db_session.commit()

        # Query back from DB and verify exact field retention
        retrieved = db_session.query(DbRawFare).filter_by(hash_id=db_fare.hash_id).one()
        assert retrieved.id is not None
        assert retrieved.origin == "DEL"
        assert retrieved.destination == "BOM"
        assert retrieved.total_fare == 5420.0
        assert retrieved.airline_code == "6E"
        assert retrieved.flight_number == "6E-205"
        assert retrieved.booking_window == "T+7"
        assert retrieved.stops == 0

    def test_dedup_hash_uniqueness_constraint_enforced(
        self,
        db_session: Session,
        sample_db_raw_fare: DbRawFare,
    ) -> None:
        """Database enforces unique constraint on hash_id, preventing duplicate quote persistence."""
        db_session.add(sample_db_raw_fare)
        db_session.commit()

        # Attempt to insert identical hash_id
        duplicate_fare = DbRawFare(
            batch_id="batch-duplicate-attempt",
            origin=sample_db_raw_fare.origin,
            destination=sample_db_raw_fare.destination,
            flight_date=sample_db_raw_fare.flight_date,
            booking_window=sample_db_raw_fare.booking_window,
            airline_code=sample_db_raw_fare.airline_code,
            flight_number=sample_db_raw_fare.flight_number,
            total_fare=sample_db_raw_fare.total_fare,
            hash_id=sample_db_raw_fare.hash_id,  # identical hash
            source_platform="another_portal",
        )

        db_session.add(duplicate_fare)
        with pytest.raises(IntegrityError):
            db_session.commit()
        db_session.rollback()

    def test_dedup_hash_reproducibility_across_layers(
        self, sample_ingestion_record: IngestionRawFareRecord
    ) -> None:
        """Hash generation algorithm must be deterministic and exactly 64-char SHA-256."""
        computed_hash = sample_ingestion_record.generate_dedup_hash()
        assert len(computed_hash) == 64
        assert int(computed_hash, 16) > 0  # valid hex number

        # Re-generating for identical input produces the identical hash
        assert sample_ingestion_record.generate_dedup_hash() == computed_hash


